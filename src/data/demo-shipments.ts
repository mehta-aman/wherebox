export function computeSummary(shipments: Shipment[]): ShipmentSummary {
  const active = shipments.filter((s) => !s.isArchived);
  return {
    total: active.length,
    inTransit: active.filter((s) => s.normalizedStatus === "IN_TRANSIT" || s.normalizedStatus === "SHIPPED" || s.normalizedStatus === "AT_FACILITY").length,
    outForDelivery: active.filter((s) => s.normalizedStatus === "OUT_FOR_DELIVERY").length,
    delivered: active.filter((s) => s.normalizedStatus === "DELIVERED").length,
    delayedOrException: active.filter((s) => s.normalizedStatus === "DELAYED" || s.normalizedStatus === "EXCEPTION" || s.normalizedStatus === "DELIVERY_ATTEMPTED").length,
  };
}
